/**
 * "Austin, TX" — the city with its state beside it. US states are abbreviated
 * so the label stays narrow; other regions are used as they arrive.
 */
export function formatPlace(city?: string, region?: string): string {
  const name = city?.trim();
  const state = region?.trim();
  if (!name) return state || 'Current location';
  if (!state || state.toLowerCase() === name.toLowerCase()) return name;
  return `${name}, ${US_STATE_ABBREVIATIONS[state.toLowerCase()] ?? state}`;
}
